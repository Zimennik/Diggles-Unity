namespace Diggles.Runtime
{
    using TMPro;
    using UnityEngine;
    using UnityEngine.UI;

    // Binding seam for the building / production panel — the original ViWinProduction. The real
    // panel is minimal: the building name plus one horizontal icon row that mixes product-order
    // cells and the available actions (pack / unpack / switch on-off / repair / buildup) in the
    // same list. This is decompile-confirmed — FUN_00521c80 rebuilds a single array at this+0x54
    // (products appended by FUN_00520620/FUN_00521310, actions inline) — and spelled out in plain
    // Tcl by info_prods.tcl (icon = data/gui/icons/$class.tga, Red$class when unaffordable, count
    // badge, repair when HP<1, energy → on/off toggle, boxed → unpack only).
    //
    // Layout is authored in the Unity editor (generated by Diggles ▸ UI ▸ Production Window,
    // refined in-scene); this holds only typed refs the controller wires to the engine seam:
    // getters get_objname / get_objtype
    // / get_prod_slot_list / get_prod_slot_buildable / get_prod_slot_cnt / get_prod_enabled / get_boxed
    // / get_attrib, setters set_prod_slot_cnt / set_prod_enabled. Icons resolve through IconLibrary.
#pragma warning disable CS0169, CS0649
    public sealed class ProductionWindow : MonoBehaviour
    {
        [SerializeField] TMP_Text? titleLabel;        // building name (get_objname)
        [SerializeField] RectTransform? listContent;  // HorizontalLayoutGroup: product + action cells
        [SerializeField] RectTransform? slotTemplate;  // one cell, cloned per slot / action
        [SerializeField] Button? scrollPrev;          // arrow_left (row scrolls when it overflows)
        [SerializeField] Button? scrollNext;          // arrow_right
        [SerializeField] IconLibrary? icons;          // class / action name → sprite
    }
#pragma warning restore CS0169, CS0649
}
